export interface BulkResultsPDFProps {
  results: {
    candidateName: string
    candidateEmail: string
    status: string
    interviewId?: string | null
    error?: string | null
  }[]
  summary: {
    total: number
    queued: number
    failed: number
    rejectedFilesCount: number
    scored?: number
    needsReview?: number
  }
  generatedAt: Date
}

function getStatusColors(status: string) {
  const key = status.toLowerCase().replace('-', '_')
  return STATUS_COLORS[key] ?? STATUS_COLORS.queued
}

export function BulkResultsPDF({ results, summary, generatedAt }: BulkResultsPDFProps) {
  const logoUrl =
    typeof window !== 'undefined'
      ? `${window.location.origin}/logo.png`
      : '/logo.png'

  const footerText = `Generated by EchoGrow — Bulk upload results  ·  ${generatedAt.toLocaleDateString('en-GB')}`

  return (
    <Document
      title="Bulk Upload Results"
      author="EchoGrow"
      subject="Bulk candidate upload summary"
    >
      <Page size="A4" style={styles.page} orientation="landscape">
        <View style={styles.header}>
          <Image src={logoUrl} style={styles.logo} />
          <View>
            <Text style={styles.brandName}>EchoGrow</Text>
            <Text style={styles.brandTagline}>Bulk Upload Results</Text>
          </View>
        </View>

        <Text style={styles.title}>Bulk Upload Summary</Text>
        <Text style={styles.subtitle}>
          {results.length} candidate(s) · {generatedAt.toLocaleDateString('en-GB')}
        </Text>

        <View style={styles.summary}>
          <View style={styles.summaryItem}>
            <Text style={styles.summaryLabel}>Total</Text>
            <Text style={styles.summaryValue}>{summary.total}</Text>
          </View>
          <View style={styles.summaryItem}>
            <Text style={styles.summaryLabel}>Scored</Text>
            <Text style={[styles.summaryValue, { color: COLORS.success }]}>
              {summary.scored ?? 0}
            </Text>
          </View>
          <View style={styles.summaryItem}>
            <Text style={styles.summaryLabel}>Needs review</Text>
            <Text style={[styles.summaryValue, { color: COLORS.warning }]}>
              {summary.needsReview ?? 0}
            </Text>
          </View>
          <View style={styles.summaryItem}>
            <Text style={styles.summaryLabel}>Failed</Text>
            <Text style={[styles.summaryValue, { color: COLORS.danger }]}>
              {summary.failed}
            </Text>
          </View>
          <View style={styles.summaryItem}>
            <Text style={styles.summaryLabel}>Rejected files</Text>
            <Text style={[styles.summaryValue, { color: COLORS.warning }]}>
              {summary.rejectedFilesCount}
            </Text>
          </View>
        </View>

        <View style={styles.tableHeader}>
          <Text style={[styles.colCandidate, styles.tableHeaderText]}>Candidate</Text>
          <Text style={[styles.colEmail, styles.tableHeaderText]}>Email</Text>
          <Text style={[styles.colStatus, styles.tableHeaderText]}>Status</Text>
          <Text style={[styles.colInterviewId, styles.tableHeaderText]}>Interview ID</Text>
        </View>

        {results.map((r, i) => {
          const colors = getStatusColors(r.status)
          return (
            <View key={i} style={styles.tableRow} wrap={false}>
              <View style={styles.colCandidate}>
                <Text style={styles.tableCell}>{r.candidateName}</Text>
                {r.error ? (
                  <Text style={[styles.tableCellMuted, { color: COLORS.danger }]}>
                    {r.error}
                  </Text>
                ) : null}
              </View>
              <View style={styles.colEmail}>
                <Text style={styles.tableCellMuted}>{r.candidateEmail}</Text>
              </View>
              <View style={styles.colStatus}>
                <View
                  style={[
                    styles.statusChipContainer,
                    { backgroundColor: colors.bg, borderColor: colors.border },
                  ]}
                >
                  <Text style={[styles.statusChipText, { color: colors.text }]}>
                    {r.status}
                  </Text>
                </View>
              </View>
              <View style={styles.colInterviewId}>
                {r.interviewId ? (
                  <Link
                    src={`${window.location.origin}/dashboard/${r.interviewId}/overview`}
                    style={styles.tableCellMuted}
                  >
                    {r.interviewId.slice(0, 12)}...
                  </Link>
                ) : (
                  <Text style={styles.tableCellMuted}>—</Text>
                )}
              </View>
            </View>
          )
        })}

        <Text style={styles.footer} fixed>
          {footerText}
        </Text>
      </Page>
    </Document>
  )
}