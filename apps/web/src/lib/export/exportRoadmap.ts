import { pdf } from '@react-pdf/renderer';
import React from 'react';
import { RoadmapPDF } from './RoadmapPDF';
import { validateRoadmapForExport, type RoadmapResponse } from '../api';

export class ExportValidationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ExportValidationError';
  }
}

/**
 * Download the roadmap as a PDF file.
 */
export async function downloadRoadmapPDF(
  candidateName: string,
  interviewDate: string,
  data: RoadmapResponse | null | undefined,
  sessionId?: string,
): Promise<void> {
  try {
    validateRoadmapForExport(data);
  } catch (cause) {
    throw new ExportValidationError(
      cause instanceof Error ? cause.message : 'Invalid roadmap data for PDF export.',
    );
  }

  try {
    const blob = await pdf(
      React.createElement(RoadmapPDF, {
        candidateName,
        interviewDate,
        data,
        sessionId,
      }) as any, // eslint-disable-line @typescript-eslint/no-explicit-any
    ).toBlob();

    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `EchoGrow-Roadmap-${candidateName.replace(/\s+/g, '-')}.pdf`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (cause) {
    throw new ExportValidationError(
      `PDF generation failed: ${cause instanceof Error ? cause.message : 'Unknown error'}`,
    );
  }
}

/**
 * Copy the roadmap as Markdown to clipboard.
 * Includes candidate name, interview date, and document ID in the header.
 */
export async function copyRoadmapMarkdown(
  candidateName: string,
  interviewDate: string,
  data: RoadmapResponse | null | undefined,
  sessionId?: string,
): Promise<void> {
  try {
    validateRoadmapForExport(data);
  } catch (cause) {
    throw new ExportValidationError(
      cause instanceof Error ? cause.message : 'Invalid roadmap data for Markdown export.',
    );
  }

  const { gaps, roadmap } = data;
  const generatedAt = new Date();
  const docId = sessionId ? sessionId.slice(-8).toUpperCase() : generatedAt.getTime().toString(36).toUpperCase().slice(-8);

  const lines: string[] = [
    `# Personalized Upskilling Roadmap`,
    '',
    `**Candidate:** ${candidateName}`,
    `**Interview Date:** ${new Date(interviewDate).toLocaleDateString('en-GB', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    })}`,
    `**Generated:** ${generatedAt.toLocaleDateString('en-GB', {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    })}`,
    `**Document ID:** ${docId}`,
    '',
    '---',
    '',
  ];

  if (gaps.length === 0) {
    lines.push('No skill gaps detected.');
  } else {
    lines.push(`## Identified Skill Gaps (${gaps.length})`, '');
    gaps.forEach((g) => lines.push(`- ${g.skillName} (${g.priority})`));
    lines.push('');
    lines.push(`## Week-by-Week Plan (${roadmap.length} weeks)`, '');

    roadmap.forEach((item) => {
      lines.push(`### Week ${item.week}: ${item.skillName}`, '');
      lines.push(item.task);
      if (item.resourceUrl) {
        lines.push('', `**Resource:** ${item.resourceUrl}`);
      }
      lines.push('');
    });
  }

  lines.push('---', '');
  lines.push(
    `_This roadmap is extracted from the candidate's own admissions during the interview — not from a fixed template. Every learning resource comes from a vetted library of official documentation and trusted tutorials._`,
  );
  lines.push('');
  lines.push(`_Generated by EchoGrow · echogrow.app · Doc ID: ${docId}_`);

  try {
    await navigator.clipboard.writeText(lines.join('\n'));
  } catch {
    throw new ExportValidationError(
      'Could not copy to clipboard. Your browser may have blocked clipboard access.',
    );
  }
}

/**
 * Download the roadmap as a JSON file.
 * Includes candidate metadata + session metadata alongside the raw roadmap.
 */
export function downloadRoadmapJSON(
  candidateName: string,
  interviewDate: string,
  data: RoadmapResponse | null | undefined,
  sessionId?: string,
): void {
  try {
    validateRoadmapForExport(data);
  } catch (cause) {
    throw new ExportValidationError(
      cause instanceof Error ? cause.message : 'Invalid roadmap data for JSON export.',
    );
  }

  const generatedAt = new Date();
  const docId = sessionId ? sessionId.slice(-8).toUpperCase() : generatedAt.getTime().toString(36).toUpperCase().slice(-8);

  const payload = {
    metadata: {
      candidateName,
      interviewDate,
      generatedAt: generatedAt.toISOString(),
      documentId: docId,
      sessionId: sessionId ?? null,
      source: 'EchoGrow — Evidence-based interview analysis',
      website: 'echogrow.app',
    },
    roadmap: data,
  };

  const blob = new Blob([JSON.stringify(payload, null, 2)], {
    type: 'application/json',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `EchoGrow-Roadmap-${candidateName.replace(/\s+/g, '-')}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}